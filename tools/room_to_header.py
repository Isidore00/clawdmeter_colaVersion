#!/usr/bin/env python3
"""assets/cola_room/*.bin -> firmware/src/room_assets.h (generated, never hand-edited).

The .bin files come from tools/room_convert.py (formats are described in its
docstring). They are copied into the header untouched except for the standing
poses, whose per-frame palette is split into rgb and alpha arrays so the
firmware can index them directly. Only firmware/src/room.cpp includes the
header.

  python tools/room_to_header.py
"""
import os
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'assets', 'cola_room')
OUT = os.path.join(ROOT, 'firmware', 'src', 'room_assets.h')

POSES = {'idle': 2, 'game': 3, 'drink': 3, 'stretch': 3,
         'surprise': 2, 'shy': 2, 'angry': 2, 'snack': 3}
SCENES = {'read': 3, 'sleep': 3}
ROOM_W = 480


def rd(name):
    with open(os.path.join(SRC, name), 'rb') as f:
        return f.read()


def arr(ctype, name, vals, per=16, fmt='0x%02X'):
    lines = []
    for i in range(0, len(vals), per):
        lines.append('    ' + ', '.join(fmt % v for v in vals[i:i + per]) + ',')
    return 'static const %s %s[] = {\n%s\n};\n' % (ctype, name, '\n'.join(lines))


def main():
    o = []
    o.append('// GENERATED by tools/room_to_header.py from assets/cola_room/*.bin; do not edit.\n'
             '// Only room.cpp includes this. Every pixel array is an LZ4 block of palette\n'
             '// indices (cola_lz4.h decodes it).\n#pragma once\n#include <stdint.h>\n')

    pal = rd('room_palette.bin')
    n = len(pal) // 2
    assert n == 255
    o.append('#define ROOM_PALETTE_N %d\n#define ROOM_W %d\n#define ROOM_H %d\n' % (n, ROOM_W, ROOM_W))
    o.append(arr('uint16_t', 'room_palette', struct.unpack('<%dH' % n, pal), 12, '0x%04X'))
    bg = rd('room_bg.bin')
    o.append(arr('uint8_t', 'room_bg_px', list(bg)))
    o.append('static const uint32_t room_bg_len = %d;\n' % len(bg))

    o.append('struct room_patch_t { uint16_t x, y, w, h; const uint8_t* px; uint32_t px_len; };\n')
    patch_names = ['room_snack_patch'] + ['room_%s_%02d' % (s, i) for s, c in SCENES.items() for i in range(1, c + 1)]
    pmax = 0
    for pn in patch_names:
        d = rd(pn + '.bin')
        x, y, w, h = struct.unpack('<HHHH', d[:8])
        pmax = max(pmax, w * h)
        o.append(arr('uint8_t', pn + '_px', list(d[8:])))
        o.append('static const room_patch_t %s = { %d, %d, %d, %d, %s_px, %d };\n' % (pn, x, y, w, h, pn, len(d) - 8))
    o.append('static const room_patch_t* const room_read_patches[%d] = { %s };\n' % (
        SCENES['read'], ', '.join('&room_read_%02d' % i for i in range(1, SCENES['read'] + 1))))
    o.append('static const room_patch_t* const room_sleep_patches[%d] = { %s };\n' % (
        SCENES['sleep'], ', '.join('&room_sleep_%02d' % i for i in range(1, SCENES['sleep'] + 1))))
    o.append('#define ROOM_PATCH_MAX_PX %d\n' % pmax)

    o.append('struct room_pose_t { uint8_t ncol; const uint16_t* rgb; const uint8_t* alpha; const uint8_t* px; uint32_t px_len; };\n')
    pw = ph = None
    for act, count in POSES.items():
        names = []
        for i in range(1, count + 1):
            nm = 'room_%s_%02d' % (act, i)
            d = rd(nm + '.bin')
            w, h, nc = struct.unpack('<HHB', d[:5])
            if pw is None: pw, ph = w, h
            assert (w, h) == (pw, ph), nm
            pal_b = d[5:5 + 3 * nc]
            rgb = [struct.unpack('<H', pal_b[3 * k:3 * k + 2])[0] for k in range(nc)]
            alpha = [pal_b[3 * k + 2] for k in range(nc)]
            px = d[5 + 3 * nc:]
            o.append(arr('uint16_t', nm + '_rgb', rgb, 12, '0x%04X'))
            o.append(arr('uint8_t', nm + '_a', alpha))
            o.append(arr('uint8_t', nm + '_px', list(px)))
            names.append((nm, nc))
        o.append('static const room_pose_t room_pose_%s[%d] = {\n%s\n};\n' % (
            act, count, '\n'.join('    { %d, %s_rgb, %s_a, %s_px, sizeof(%s_px) },' % (
                nc, n, n, n, n) for n, nc in names)))
    # room_convert.py puts the soles 4 px above the bottom edge, centre line at W/2: the rug anchor
    o.append('#define ROOM_POSE_W %d\n#define ROOM_POSE_H %d\n#define ROOM_POSE_GROUND %d\n' % (pw, ph, ph - 4))
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(o))
    print('wrote', os.path.relpath(OUT, ROOT), os.path.getsize(OUT), 'bytes')


if __name__ == '__main__':
    main()
