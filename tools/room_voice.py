#!/usr/bin/env python3
"""Room voice clips: assets/cola_room/room_*.mp3 -> firmware/src/room_voice_assets.h.

For each clip, in the order of ROOM_VOICES (the same order as the RoomVoice
enum in firmware/src/room_policy.h):

  1. decode with ffmpeg to 16 kHz mono 16-bit
  2. trim the silence at both ends (below TRIM_DB of the clip's own peak,
     keeping PAD_MS of lead-in and tail), with a short fade so the cut doesn't click
  3. peak-normalise to PEAK of full scale, the same for every clip
  4. encode as IMA ADPCM, 4 bits a sample, low nibble first, predictor 0 /
     step index 0 at the start (firmware/src/adpcm.cpp decodes it)

The MP3s stay in assets/; only the generated header goes into the firmware.
The firmware resamples 16 kHz to the codec's rate while it plays.

Needs: ffmpeg on PATH, pip install numpy. Run from anywhere:

  python tools/room_voice.py
"""
import os
import subprocess
import sys

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'assets', 'cola_room')
OUT = os.path.join(ROOT, 'firmware', 'src', 'room_voice_assets.h')

# file stem (room_<stem>.mp3) in RoomVoice order
ROOM_VOICES = ['poke_surprise', 'poke_shy', 'poke_angry', 'love', 'iloveyou',
               'morning', 'night', 'snack', 'drink']
RATE = 16000
PEAK = 0.70          # of full scale; the ding peaks at about the same
TRIM_DB = -42
PAD_MS = 25
FADE_MS = 8
BUDGET = 200 * 1024

STEPS = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66,
         73, 80, 88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408,
         449, 494, 544, 598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066,
         2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630,
         9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623, 27086, 29794,
         32767]
INDEX = [-1, -1, -1, -1, 2, 4, 6, 8]


def decode_mp3(path):
    r = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', str(RATE),
                        '-f', 's16le', '-'], capture_output=True, check=True)
    return np.frombuffer(r.stdout, dtype='<i2').astype(np.float64)


def trim(x):
    thr = np.abs(x).max() * 10 ** (TRIM_DB / 20)
    loud = np.where(np.abs(x) > thr)[0]
    pad = RATE * PAD_MS // 1000
    a, b = max(0, loud[0] - pad), min(len(x), loud[-1] + 1 + pad)
    y = x[a:b].copy()
    f = min(RATE * FADE_MS // 1000, len(y) // 2)
    ramp = np.linspace(0, 1, f)
    y[:f] *= ramp
    y[-f:] *= ramp[::-1]
    return y


def encode(pcm):
    """IMA ADPCM, the same arithmetic as the firmware's decoder."""
    pred, idx = 0, 0
    nib = []
    for s in pcm:
        step = STEPS[idx]
        diff = int(s) - pred
        code = 0
        if diff < 0:
            code, diff = 8, -diff
        if diff >= step: code |= 4; diff -= step
        if diff >= step >> 1: code |= 2; diff -= step >> 1
        if diff >= step >> 2: code |= 1
        d = step >> 3
        if code & 4: d += step
        if code & 2: d += step >> 1
        if code & 1: d += step >> 2
        pred = max(-32768, min(32767, pred - d if code & 8 else pred + d))
        idx = max(0, min(88, idx + INDEX[code & 7]))
        nib.append(code)
    if len(nib) & 1: nib.append(0)
    return bytes(nib[i] | (nib[i + 1] << 4) for i in range(0, len(nib), 2)), pred


def main():
    out = ['// GENERATED by tools/room_voice.py from assets/cola_room/room_*.mp3; do not edit.',
           '// Only room.cpp includes this. IMA ADPCM, mono, 16 kHz, low nibble first,',
           '// decoder state 0 at the start (adpcm.h). Order = the RoomVoice enum.',
           '#pragma once', '#include <stdint.h>', '',
           'struct room_voice_t { const uint8_t* adpcm; uint32_t samples; uint32_t rate; };', '']
    rows, total = [], 0
    for name in ROOM_VOICES:
        x = decode_mp3(os.path.join(SRC, 'room_%s.mp3' % name))
        raw_s = len(x) / RATE
        x = trim(x)
        x = np.round(x * (PEAK * 32767 / np.abs(x).max()))
        data, _ = encode(x)
        total += len(data)
        lines = ['    ' + ', '.join('0x%02X' % b for b in data[i:i + 20]) + ',' for i in range(0, len(data), 20)]
        out.append('static const uint8_t room_voice_%s_adpcm[] = {\n%s\n};' % (name, '\n'.join(lines)))
        rows.append('    { room_voice_%s_adpcm, %d, %d },   // %s' % (name, len(x), RATE, name))
        print('%-14s %5.2f s -> %5.2f s  %6d B' % (name, raw_s, len(x) / RATE, len(data)))
    out.append('\n#define ROOM_VOICE_N %d' % len(ROOM_VOICES))
    out.append('static const room_voice_t room_voices[ROOM_VOICE_N] = {\n%s\n};\n' % '\n'.join(rows))
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('total %d B (budget %d B)' % (total, BUDGET))
    if total > BUDGET:
        sys.exit('over the size budget')


if __name__ == '__main__':
    main()
